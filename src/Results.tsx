// ---------- Small building blocks ----------

const RISKISH = { low: "good", medium: "ok", high: "bad" } as const; // low is good
const CONF = { low: "bad", medium: "ok", high: "good" } as const; // high is good

function Pill({ level, invert, label }: { level: Level; invert?: boolean; label?: string }) {
  const cls = (invert ? RISKISH : CONF)[level] ?? "ok";
  return (
    <span className={`pill ${cls}`}>
      {label ? `${label}: ` : ""}
      {level}
    </span>
  );
}

/** A coloured, boxed section. tone sets the colour. */
function Box({ tone, icon, title, children, className = "" }: { tone: "green" | "amber" | "blue" | "grey" | "purple"; icon: string; title: string; children: ReactNode; className?: string }) {
  return (
    <section className={`box box-${tone} ${className}`}>
      <h3 className="box-title">
        <span className="box-icon" aria-hidden="true">
          {icon}
        </span>
        {title}
      </h3>
      {children}
    </section>
  );
}

function Bullets({ items }: { items: string[] }) {
  return (
    <ul className="box-list">
      {items.map((x, i) => (
        <li key={i}>{x}</li>
      ))}
    </ul>
  );
}

/** Collapsed by default: things most readers can skip. */
function More({ title, count, children }: { title: string; count?: number; children: ReactNode }) {
  return (
    <details className="more">
      <summary>
        {title}
        {count !== undefined && <span className="count">{count}</span>}
      </summary>
      <div className="more-body">{children}</div>
    </details>
  );
}

function NextStep({ s }: { s: { action: string; owner: string; within: string } }) {
  if (!s.action) return null;
  return (
    <section className="nextstep">
      <div className="nextstep-main">
        <p className="nextstep-label">Pippa suggests</p>
        <p className="nextstep-action">{s.action}</p>
        <dl className="nextstep-meta">
          <div>
            <dt>Who</dt>
            <dd>{s.owner}</dd>
          </div>
          <div>
            <dt>When</dt>
            <dd>Within {s.within}</dd>
          </div>
        </dl>
      </div>
      <div className="nextstep-online no-print">
        <div>
          <p className="online-title">Take Pippa online</p>
          <p className="online-text">Live search for open calls, deadline tracking and funder alerts, matched to this case.</p>
        </div>
        {session.online ? (
          <a className="upgrade open" href="#/online">
            Open Pippa Online
          </a>
        ) : (
        <button className="upgrade" disabled title="Coming soon" aria-label="Upgrade, coming soon">
          <svg viewBox="0 0 16 16" width="14" height="14" aria-hidden="true">
            <rect x="3" y="7" width="10" height="7" rx="1.5" fill="none" stroke="currentColor" strokeWidth="1.5" />
            <path d="M5.5 7V5a2.5 2.5 0 0 1 5 0v2" fill="none" stroke="currentColor" strokeWidth="1.5" />
          </svg>
          Upgrade
        </button>
        )}
      </div>
    </section>
  );
}

const AiNote = () => <p className="ai-note">Generated by AI from what you gave Pippa. Check facts against the original sources before acting.</p>;

/** The result plus the Ask Pippa panel. */
export function ResultView({ tool, output, runId }: { tool: Tool | "search"; output: unknown; runId?: string }) {
  return (
    <>
      {tool === "search" ? (
        <SearchCard r={output as SearchResult} />
      ) : tool === "funder" ? (
        <FunderCard r={output as FunderResult} />
      ) : (
        <ResourcesCard r={output as ResourcesResult} />
      )}
      {runId && <AskPippa runId={runId} tool={tool} />}
    </>
  );
}

// ---------- Funder check ----------

const VERDICT_TONE: Record<string, string> = { Pursue: "good", "Pursue narrowly": "teal", Hold: "ok", "Don't pursue": "bad" };
const VERDICT_LINE: Record<string, string> = {
  Pursue: "Worth a full approach now.",
  "Pursue narrowly": "Worth it, but only through a specific angle.",
  Hold: "Not yet. A key fact is missing or the timing is off.",
  "Don't pursue": "Not worth your time for this ask.",
};

function Gauge({ label, value, invert, reason }: { label: string; value: number; invert?: boolean; reason: string }) {
  const good = invert ? 100 - value : value;
  const cls = good >= 70 ? "good" : good >= 45 ? "ok" : "bad";
  const word = invert ? (value < 30 ? "Little bending" : value < 60 ? "Some bending" : "Major bending") : value >= 70 ? "Strong" : value >= 45 ? "Partial" : "Weak";
  return (
    <div className="gauge">
      <div className="gauge-top">
        <span className="gauge-label">{label}</span>
        <span className={`gauge-word ${cls}`}>{word}</span>
      </div>
      <div className="gauge-num">
        {value}
        <span>/100</span>
      </div>
      <div className="bar">
        <div className={`fill ${cls}`} style={{ width: `${Math.max(3, Math.min(100, value))}%` }} />
      </div>
      {reason && <p className="gauge-reason">{reason}</p>}
    </div>
  );
}

export function FunderCard({ r: raw }: { r: FunderResult }) {
  const r = normalizeFunder(raw);
  const tone = VERDICT_TONE[r.verdict] ?? "ok";
  const sc = r.scores;
  const hasScores = [sc.material, sc.symbolic, sc.drift].some((x) => x.score > 0 || x.reason);
  return (
    <article className="result">
      <header className={`hero hero-${tone}`}>
        <p className="eyebrow">Funder check · {r.funder_name}</p>
        <div className="hero-verdict">
          <span className="hero-word">{r.verdict}</span>
          <span className="hero-conf">Confidence: {r.confidence}</span>
        </div>
        <p className="hero-sub">{VERDICT_LINE[r.verdict]}</p>
        {r.summary && <p className="hero-text">{r.summary}</p>}
        {r.would_change_if && (
          <p className="hero-note">
            <strong>Would change if:</strong> {r.would_change_if}
          </p>
        )}
      </header>

      {hasScores ? (
        <>
          <div className="gauges">
            <Gauge label="Material fit" value={r.scores.material.score} reason={r.scores.material.reason} />
            <Gauge label="Symbolic fit" value={r.scores.symbolic.score} reason={r.scores.symbolic.reason} />
            <Gauge label="Drift risk" value={r.scores.drift.score} reason={r.scores.drift.reason} invert />
          </div>
          <FunderLegend />
        </>
      ) : (
        <p className="muted small">Fit scores weren't returned for this run. The verdict rests on the reasoning above.</p>
      )}

      {r.hard_checks.length > 0 && (
        <section className="checks">
          <h3 className="section-title">Eligibility checks</h3>
          <div className="elig-grid">
            {r.hard_checks.map((c, i) => (
              <div className={`elig elig-${c.status}`} key={i}>
                <span className="elig-icon" aria-label={c.status}>
                  {c.status === "pass" ? "✓" : c.status === "fail" ? "✕" : "?"}
                </span>
                <div>
                  <strong>{c.check}</strong>
                  {c.note && <p>{c.note}</p>}
                </div>
              </div>
            ))}
          </div>
        </section>
      )}

      <div className="box-row">
        {r.route_in.route && (
          <Box tone="blue" icon="→" title="Best route in">
            <p className="box-lead">{r.route_in.route}</p>
            {r.route_in.why && <p>{r.route_in.why}</p>}
          </Box>
        )}
        {r.what_funder_gets.length > 0 && (
          <Box tone="green" icon="✓" title="What they get from you">
            <Bullets items={r.what_funder_gets} />
          </Box>
        )}
      </div>

      <div className="box-row">
        {r.positioning.length > 0 && (
          <Box tone="blue" icon="✎" title="How to frame the ask">
            <ol className="box-list numbered">
              {r.positioning.map((p, i) => (
                <li key={i}>{p}</li>
              ))}
            </ol>
          </Box>
        )}
        {r.internal_leverage.length > 0 && (
          <Box tone="green" icon="⌂" title="What to bring">
            <Bullets items={r.internal_leverage} />
          </Box>
        )}
      </div>

      {r.systems_change && (
        <Box tone="purple" icon="◎" title="Bigger picture: systems change">
          <p>{r.systems_change}</p>
        </Box>
      )}

      <NextStep s={r.next_step} />

      <div className="mores">
        {r.questions_they_will_ask.length > 0 && (
          <More title="Questions they'll probably ask you" count={r.questions_they_will_ask.length}>
            <Bullets items={r.questions_they_will_ask} />
          </More>
        )}
        {r.unverified.length > 0 && (
          <More title="What Pippa couldn't confirm" count={r.unverified.length}>
            <Bullets items={r.unverified} />
          </More>
        )}
      </div>
      <AiNote />
    </article>
  );
}

// ---------- Internal resources ----------

const TYPE_LABEL: Record<Opportunity["type"], string> = { human: "People", material: "Assets", project: "Programme capacity", saving: "Saving" };

const rank = (o: Opportunity) => ({ low: 2, medium: 1, high: 0 })[o.mission_risk] + ({ low: 2, medium: 1, high: 0 })[o.effort] + ({ high: 2, medium: 1, low: 0 })[o.confidence];

function OppCard({ o }: { o: Opportunity }) {
  const [open, setOpen] = useState(false);
  return (
    <div className={`opp-card type-${o.type}`}>
      <span className="type-tag">{TYPE_LABEL[o.type]}</span>
      <h4>{o.title}</h4>
      <p>{o.how}</p>
      <div className="opp-pills">
        <Pill level={o.mission_risk} invert label="Risk" />
        <Pill level={o.effort} invert label="Effort" />
        <Pill level={o.confidence} label="Confidence" />
      </div>
      {(o.source || o.approval) && (
        <>
          <button className="link details-toggle" onClick={() => setOpen(!open)} aria-expanded={open}>
            {open ? "Hide details" : "Where this comes from"}
          </button>
          {open && (
            <dl className="opp-details">
              {o.source && (
                <>
                  <dt>From your document</dt>
                  <dd>{o.source}</dd>
                </>
              )}
              {o.approval && (
                <>
                  <dt>Who approves</dt>
                  <dd>{o.approval}</dd>
                </>
              )}
            </dl>
          )}
        </>
      )}
    </div>
  );
}

export function ResourcesCard({ r: raw }: { r: ResourcesResult }) {
  const r = normalizeResources(raw);
  const sorted = [...r.opportunities].sort((a, b) => rank(b) - rank(a));
  const best = sorted.slice(0, 3);
  const rest = sorted.slice(3);
  const plan = r.top[0];

  return (
    <article className="result">
      <header className="hero hero-good">
        <p className="eyebrow">Internal resources · {r.document_type}</p>
        {r.headline && <p className="hero-text big">{r.headline}</p>}
        {r.document_summary && <p className="hero-note">{r.document_summary}</p>}
      </header>

      {best.length > 0 ? (
        <section>
          <h3 className="section-title">Best bets</h3>
          <div className="opp-grid">
            {best.map((o, i) => (
              <OppCard o={o} key={i} />
            ))}
          </div>
          <ResourcesLegend />
        </section>
      ) : (
        <Box tone="grey" icon="i" title="No strong opportunities found">
          <p>Pippa didn't find idle or underused resources that fit this need. Try a different document, such as a budget or programme report.</p>
        </Box>
      )}

      {plan && (
        <section className="plan">
          <h3 className="section-title">How the best one would work: {plan.title}</h3>
          <ol className="plan-strip">
            {(
              [
                ["What you have", plan.asset],
                ["How it earns or saves", plan.model],
                ["Who pays or benefits", plan.who_pays],
                ["Why it matters", plan.impact],
                ["First step", plan.first_step],
              ] as [string, string][]
            )
              .filter(([, v]) => v)
              .map(([k, v]) => (
                <li key={k}>
                  <span className="plan-k">{k}</span>
                  <span className="plan-v">{v}</span>
                </li>
              ))}
          </ol>
          {plan.approver && <p className="muted small">Approval: {plan.approver}</p>}
        </section>
      )}

      <div className="box-row">
        {r.leverage.length > 0 && (
          <Box tone="green" icon="✓" title="Bring to funders as co-financing">
            <Bullets items={r.leverage} />
          </Box>
        )}
        {r.cautions.length > 0 && (
          <Box tone="amber" icon="!" title="Watch out">
            <Bullets items={r.cautions} />
          </Box>
        )}
      </div>

      <NextStep s={r.next_step} />

      <div className="mores">
        {rest.length > 0 && (
          <More title="More ideas" count={rest.length}>
            <div className="opp-grid">
              {rest.map((o, i) => (
                <OppCard o={o} key={i} />
              ))}
            </div>
          </More>
        )}
        {r.top.length > 1 && (
          <More title="Another worked example">
            {r.top.slice(1).map((t, i) => (
              <dl className="opp-details" key={i}>
                <dt>{t.title}</dt>
                <dd>
                  {[t.asset, t.model, t.who_pays, t.impact, t.first_step].filter(Boolean).join(" → ")}
                </dd>
              </dl>
            ))}
          </More>
        )}
        {r.unverified.length > 0 && (
          <More title="What Pippa couldn't confirm" count={r.unverified.length}>
            <Bullets items={r.unverified} />
          </More>
        )}
      </div>
      <AiNote />
    </article>
  );
}
